import type { CuisineType, Ingredient, InstructionStep, SubRecipe } from "@sofria/shared";

/**
 * Gerçek kullanıcı talebi: haftalık plan artık LLM'in serbestçe uydurduğu
 * tariflerden değil, BURADAKİ sabit tariflerden oluşuyor — öğle/akşam
 * tariflerinin çoğu için gerçek görsel mevcut (bkz. apps/web/public/dish-images/,
 * apps/mobile/assets/images/dishes/, dosya adı = `imageSlug`).
 *
 * Bu, F5'teki tüm LLM güvenilmezlik sınıfını (kota, bozuk JSON, kural ihlali,
 * düzeltme turu) ortadan kaldırır — seçim BURADA, kod tarafında, deterministik
 * yapılır (bkz. catalogPlanBuilder.ts). `servings` her tarifin YAZILDIĞI
 * temel porsiyon sayısıdır; gerçek hane büyüklüğüne göre malzeme miktarları
 * catalogPlanBuilder.ts içinde ORANTILI olarak ölçeklenir.
 */
export interface CatalogRecipe {
  slug: string;
  name: string;
  role: SubRecipe["role"];
  /** Bu tarifin "yakıştığı" mutfak kategorileri — dağıtım bunlardan seçilir. */
  cuisineTags: CuisineType[];
  servings: number;
  prepMinutes: number;
  cookMinutes: number;
  difficulty: SubRecipe["difficulty"];
  estimatedKcalPerServing: number;
  requiredEquipment: string[];
  dietary: { vegetarian: boolean; vegan: boolean; glutenFree: boolean; lactoseFree: boolean };
  ingredients: Ingredient[];
  instructions: InstructionStep[];
  /** dish-images/<imageSlug>.jpg ve assets/images/dishes/<imageSlug>.jpg — bkz. üstteki not. */
  imageSlug: string;
  /**
   * Yalnızca kahvaltı öğününde seçilir (öğle/akşamda ASLA). Kahvaltı,
   * mutfak seçiminden bağımsızdır (bkz. eski cuisine.fragment.ts BREAKFAST_NOTE
   * mantığı) — bu yüzden cuisineTags bu kayıtlarda tüm kategorileri kapsar.
   * Bu 6 kahvaltılığın GERÇEK görseli henüz yok (orijinal 70'lik listeye
   * dahil değillerdi) — UI, imageSlug bulunamazsa role ikonuna düşer.
   */
  isBreakfast?: boolean;
  /**
   * Gerçek kullanıcı talebi: bazı tarif çiftleri aynı öğünde ANLAMSIZ/
   * gereksiz tekrar oluşturuyor (örn. İzmir Köfte zaten patates içeriyorken
   * yanına ayrıca patates kızartması gelmesi gibi). Buraya yazılan slug'lar
   * aynı öğünde ASLA birlikte seçilmez — kontrol İKİ YÖNLÜ yapılır (bkz.
   * catalogPlanBuilder.ts isIncompatible), yani yalnızca bir tarafa yazmak
   * yeterlidir.
   */
  incompatibleWith?: string[];
}

