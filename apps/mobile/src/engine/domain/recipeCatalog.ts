function ing(slug: string, displayName: string, amount: number, unit: Ingredient["unit"], isPantryStaple = false, note?: string): Ingredient {
  return note ? { slug, displayName, amount, unit, isPantryStaple, note } : { slug, displayName, amount, unit, isPantryStaple };
}
function step(order: number, text: string): InstructionStep {
  return { order, text };
}

